#!/usr/bin/env node
/**
 * Writes dist/index.js — compatibility entry for `node dist/index.js`.
 * The compiled server lives at dist/server/index.js (tsup output).
 */
const fs = require('node:fs');
const path = require('node:path');

const distDir = path.join(__dirname, '..', 'dist');
const serverEntry = path.join(distDir, 'server', 'index.js');
const shimPath = path.join(distDir, 'index.js');

if (!fs.existsSync(serverEntry)) {
  console.error(`[write-server-entry-shim] missing ${serverEntry} — run build:server first`);
  process.exit(1);
}

// tsup/esbuild rewrites `node:sqlite` → `sqlite` when bundling; patch for Node 22 builtin.
let serverCode = fs.readFileSync(serverEntry, 'utf8');
const patched = serverCode.replace(/from "sqlite"/g, 'from "node:sqlite"');
if (patched !== serverCode) {
  fs.writeFileSync(serverEntry, patched);
  console.log('[write-server-entry-shim] patched sqlite imports -> node:sqlite');
}

const shim = `// Generated by scripts/write-server-entry-shim.cjs — do not edit.
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = dirname(fileURLToPath(import.meta.url));
const child = spawn(process.execPath, [join(dir, 'server', 'index.js')], {
  stdio: 'inherit',
  env: process.env,
});

function forwardSignal(signal) {
  if (!child.killed) {
    try {
      child.kill(signal);
    } catch {
      // child already gone
    }
  }
}

process.on('SIGTERM', () => forwardSignal('SIGTERM'));
process.on('SIGINT', () => forwardSignal('SIGINT'));

child.on('exit', (code, signal) => {
  if (signal) process.kill(process.pid, signal);
  process.exit(code ?? 1);
});
`;

fs.mkdirSync(distDir, { recursive: true });
fs.writeFileSync(shimPath, shim);
console.log(`[write-server-entry-shim] wrote ${shimPath}`);
